"""Teacher dashboard: class-wide gaps, misconceptions, AI brief, student drill-down."""
import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from tutor import analytics, learner_model, ui
from tutor.agents.insights import brief

st.set_page_config(page_title="Teacher · QueryMind", page_icon="👩‍🏫", layout="wide")
conn, graph, notes, llm = ui.services()
ui.sidebar()
st.title("👩‍🏫 Teacher dashboard")
st.caption("BE23CS405 Database Management System · class-wide view")

f1, f2 = st.columns([1, 3])
inc_sim = f1.toggle("Include simulated class", value=True)
inc_real = f1.toggle("Include real students", value=True)
roster = analytics.class_students(conn, inc_sim, inc_real)
ids = [r["id"] for r in roster]
names = {r["id"]: r["display_name"] for r in roster}
if not ids or not conn.execute("SELECT 1 FROM responses LIMIT 1").fetchone():
    st.info("No class data yet. Run `python scripts/simulate_class.py` to create a demo class of 25 students.")
    st.stop()

mc_stats = analytics.misconception_stats(conn, ids)
gaps = analytics.concept_gaps(conn, graph, ids)
k1, k2, k3, k4 = st.columns(4)
k1.metric("Students", len(ids))
vals = [v for row in analytics.mastery_matrix(conn, ids, graph.core_ids()) for v in row if v is not None]
k2.metric("Class mean mastery", f"{sum(vals) / len(vals):.0%}" if vals else "–")
k3.metric("Active misconceptions", sum(len(m.active) for m in mc_stats))
k4.metric("Answers recorded", conn.execute(
    f"SELECT COUNT(*) FROM responses WHERE student_id IN ({','.join('?' * len(ids))})", ids).fetchone()[0])

tab_over, tab_heat, tab_mc, tab_student = st.tabs(["📋 Brief & gaps", "🔥 Heatmap", "🧠 Misconceptions",
                                                    "🔍 Student drill-down"])

with tab_over:
    left, right = st.columns([3, 2], gap="large")
    with left:
        st.markdown("#### 🤖 What to re-teach next class")
        refresh = st.button("Regenerate brief", disabled=llm is None)
        with st.spinner("Writing the brief…"):
            b = brief(conn, graph, llm, ids, refresh=refresh)
        st.markdown(f"**{b.headline}**")
        for i, g in enumerate(b.gaps, 1):
            st.markdown(f"**{i}. {g.concept}**  \n{g.why}  \n🧑‍🏫 _{g.activity}_")
        if b.students_to_watch:
            st.markdown("**Check in with:** " + "; ".join(f"{w.student} ({w.reason})" for w in b.students_to_watch))
        st.caption("Generated by the Class Insights agent" if b.source == "llm" else
                   "Rule-based summary (add a GROQ_API_KEY for the AI brief)")
    with right:
        st.markdown("#### Weakest concepts")
        df = pd.DataFrame([{"Concept": graph.concepts[g.concept_id].name, "Unit": graph.concepts[g.concept_id].unit,
                            "Class mean": round(g.mean * 100), "Struggling": f"{g.n_struggling}/{g.n_assessed}"}
                           for g in gaps[:8]])
        st.dataframe(df, hide_index=True, width="stretch", column_config={
            "Class mean": st.column_config.ProgressColumn(min_value=0, max_value=100, format="%d%%")})
        um = analytics.unit_means(conn, graph, ids)
        st.markdown("#### By unit")
        st.bar_chart(pd.DataFrame({"Mastery %": {f"U{u}": round(v * 100) for u, v in um.items()}}),
                     horizontal=True, height=220)

with tab_heat:
    core_only = st.toggle("Demo-core concepts only", value=True, key="heat_core")
    concept_ids = graph.core_ids() if core_only else [c for c in graph.topo_order()]
    concept_ids = sorted(concept_ids, key=lambda c: (graph.concepts[c].unit, graph.topo_order().index(c)))
    m = analytics.mastery_matrix(conn, ids, concept_ids)
    keep = [j for j, _ in enumerate(concept_ids) if any(row[j] is not None for row in m)]
    z = [[None if row[j] is None else round(row[j] * 100) for j in keep] for row in m]
    x = [f"U{graph.concepts[concept_ids[j]].unit} · {graph.concepts[concept_ids[j]].name}" for j in keep]
    fig = go.Figure(go.Heatmap(z=z, x=x, y=[names[s] for s in ids], ygap=1, xgap=1, zmin=0, zmax=100,
                               colorscale=[[0, "#ef4444"], [0.4, "#f59e0b"], [0.7, "#84cc16"], [1, "#16a34a"]],
                               hovertemplate="%{y}<br>%{x}<br>mastery %{z}%<extra></extra>",
                               colorbar=dict(title="Mastery %")))
    fig.update_layout(height=max(420, 22 * len(ids)), margin=dict(l=10, r=10, t=10, b=10),
                      xaxis=dict(tickangle=-45, side="top"),
                      yaxis=dict(autorange="reversed", tickmode="linear", dtick=1))
    st.plotly_chart(fig, width="stretch")
    st.caption("Blank = not attempted yet. Hover a cell for details.")

with tab_mc:
    rows = []
    for s in mc_stats[:15]:
        m = graph.misconceptions[s.misconception_id]
        rows.append({"Misconception": m.belief, "Active": len(s.active), "Suspected": len(s.suspected),
                     "Resolved": len(s.resolved),
                     "Concepts": ", ".join(graph.concepts[c].name for c in m.concepts),
                     "Students (active)": ", ".join(names[x] for x in s.active),
                     "Fix": m.remediation})
    st.dataframe(pd.DataFrame(rows), hide_index=True, width="stretch", column_config={
        "Active": st.column_config.ProgressColumn(min_value=0, max_value=len(ids), format="%d")})

with tab_student:
    sid = st.selectbox("Student", ids, format_func=names.get)
    c1, c2 = st.columns([3, 2], gap="large")
    with c1:
        ui.mastery_map(graph, sid)
    with c2:
        st.markdown("#### Misconceptions")
        ui.active_misconceptions(sid)
        attempted = learner_model.get_all(conn, sid, attempted_only=True)
        if attempted:
            st.markdown("#### Weakest concepts")
            for cid, p in sorted(attempted.items(), key=lambda kv: kv[1])[:5]:
                st.markdown(f"- {graph.concepts[cid].name}: **{p:.0%}**")
    st.markdown("#### Recent answers")
    rr = analytics.recent_responses(conn, sid, 25)
    st.dataframe(pd.DataFrame([{"When": r["created_at"][:16].replace("T", " "),
                                "Concept": graph.concepts[r["concept_id"]].name, "Question": r["stem"][:90],
                                "Answer": (r["answer"] or "")[:80], "Reasoning": r["reasoning"],
                                "Correct": "✅" if r["correct"] else "❌", "Diagnosis": r["diagnosis"] or ""}
                               for r in rr]), hide_index=True, width="stretch")
